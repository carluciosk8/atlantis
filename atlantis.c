//-----------------------------------------------------------------------------
/// Program entry point
void main(void)
{
	// Screen 2 (Graphic 2), 256×192
	VDP_SetMode(VDP_MODE_SCREEN2);

	// Halt until the next vertical blank, forever
	for (;;)
	{
		Halt();
	}
}
