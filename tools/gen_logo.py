#!/usr/bin/env python3
"""Generate src/data/logo_data.c and logo_data.h from assets/gfx/logo.png.

Run it from the repository root with `python3 -I tools/gen_logo.py` (needs
Pillow).

logo.png is the title logo as it appears on screen: LOGO_W x LOGO_H tiles, drawn
at name-table position (LOGO_X, LOGO_Y), painted with the colours of MSXimg's
MSX1 palette, with at most 2 colours in each 8x1 tile row. The image is cut into
8x8 tiles, equal tiles are merged, and black cells use the font's space tile.

The title screen loads the logo tiles into the top pattern bank, in the slot
ranges of SLOT_RANGES: slots that no game screen shows in rows 0..7, or that the
sky code reloads before it shows them.
"""
import os
import sys

from PIL import Image

LOGO_X, LOGO_Y = 4, 1
LOGO_W, LOGO_H = 24, 7
BLANK = 0x20                  # the space tile

# { first slot, count }: the old logo and moon slots (the moon is only shown in
# the middle bank), the night beam pool, and the unloaded, cloud and bird slots.
SLOT_RANGES = [(0x00, 29), (0x60, 23), (0xD5, 43)]

BLACK = 1
PALETTE = {                   # RGB in logo.png -> MSX colour
    (0, 0, 0): BLACK,
    (68, 68, 221): 4,         # dark blue
    (119, 119, 255): 5,       # light blue
    (119, 221, 221): 7,       # cyan
    (204, 204, 85): 10,       # dark yellow
    (238, 238, 136): 11,      # light yellow
    (238, 238, 238): 15,      # white
}


def encode(image, tx, ty):
    """Return (patterns, colors) of the tile at (tx, ty), 8 bytes each."""
    patterns, colors = [], []
    for y in range(ty * 8, ty * 8 + 8):
        row = []
        for x in range(tx * 8, tx * 8 + 8):
            rgb = image.getpixel((x, y))
            if rgb not in PALETTE:
                sys.exit(f"pixel ({x}, {y}): colour {rgb} is not in PALETTE")
            row.append(PALETTE[rgb])
        used = sorted(set(row))
        if len(used) > 2:
            sys.exit(f"pixel row ({tx * 8}..{tx * 8 + 7}, {y}) has more than 2 colours")
        # Black is the background where present; else the lower colour number.
        background = BLACK if BLACK in used or len(used) == 1 else used[0]
        foreground = used[-1] if used[-1] != background else used[0]
        patterns.append(sum(0x80 >> i for i, c in enumerate(row) if c != background))
        colors.append(foreground << 4 | background)
    return tuple(patterns), tuple(colors)


def hex_row(values):
    return ",".join(f"0x{v:02X}" for v in values)


def main():
    image = Image.open("assets/gfx/logo.png").convert("RGB")
    if image.size != (LOGO_W * 8, LOGO_H * 8):
        sys.exit(f"logo.png is {image.size}, expected {(LOGO_W * 8, LOGO_H * 8)}")

    slots = [first + i for first, count in SLOT_RANGES for i in range(count)]
    tiles = []                # unique (patterns, colors), in order of first use
    names = []
    for ty in range(LOGO_H):
        for tx in range(LOGO_W):
            tile = encode(image, tx, ty)
            if not any(tile[0]) and all(c & 15 == BLACK for c in tile[1]):
                names.append(BLANK)
                continue
            if tile not in tiles:
                tiles.append(tile)
            index = tiles.index(tile)
            if index >= len(slots):
                sys.exit(f"the logo needs more than {len(slots)} tiles")
            names.append(slots[index])

    ranges = []               # the slot ranges actually used
    left = len(tiles)
    for first, count in SLOT_RANGES:
        if left > 0:
            ranges.append((first, min(count, left)))
            left -= count

    header = f"""#pragma once

#include "msxgl.h"


// Title logo: const tables only, no code. Generated by tools/gen_logo.py from
// assets/gfx/logo.png; do not edit by hand.

// Position and size on the title screen, in tiles.
#define LOGO_X                 {LOGO_X}
#define LOGO_Y                 {LOGO_Y}
#define LOGO_W                 {LOGO_W}
#define LOGO_H                 {LOGO_H}

// The logo tiles are loaded into the top pattern and colour banks, split into
// these slot ranges: {{ first slot, count }}. The tables hold them in that order.
#define LOGO_TILES             {len(tiles)}
#define LOGO_SLOT_RANGES       {len(ranges)}
extern const u8 logo_slots[LOGO_SLOT_RANGES][2];
extern const u8 logo_patterns[LOGO_TILES*8];
extern const u8 logo_colors[LOGO_TILES*8];

// Name-table cells, row by row (0x{BLANK:02X} = blank).
extern const u8 logo_names[LOGO_H*LOGO_W];
"""

    code = ['#include "logo_data.h"', "", "",
            "// Generated by tools/gen_logo.py from assets/gfx/logo.png; do not edit by hand.",
            "",
            "const u8 logo_slots[LOGO_SLOT_RANGES][2] =", "{",
            "    " + " ".join(f"{{ 0x{first:02X}, {count} }}," for first, count in ranges),
            "};", ""]
    for table, part in (("logo_patterns", 0), ("logo_colors", 1)):
        code += [f"const u8 {table}[LOGO_TILES*8] =", "{"]
        code += [f"    {hex_row(tile[part])},   // 0x{slots[i]:02X}" for i, tile in enumerate(tiles)]
        code += ["};", ""]
    code += ["const u8 logo_names[LOGO_H*LOGO_W] =", "{"]
    code += [f"    {hex_row(names[r * LOGO_W:(r + 1) * LOGO_W])}," for r in range(LOGO_H)]
    code += ["};"]

    for path, text in (("src/data/logo_data.h", header), ("src/data/logo_data.c", "\n".join(code) + "\n")):
        with open(path, "w", newline="\n") as f:
            f.write(text)
    used = ", ".join(f"0x{first:02X}..0x{first + count - 1:02X}" for first, count in ranges)
    print(f"{len(tiles)} tiles in {used} ({len(slots)} slots available)", file=sys.stderr)


if __name__ == "__main__":
    main()
